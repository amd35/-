const I18nContext = createContext(null)
const STORAGE_KEY = 'tonvoice.lang'

export function I18nProvider({ children }) {
  const [lang, setLang] = useState(() => window.localStorage.getItem(STORAGE_KEY) || 'ar')

  useEffect(() => {
    window.localStorage.setItem(STORAGE_KEY, lang)
    document.documentElement.lang = lang
    document.documentElement.dir = lang === 'ar' ? 'rtl' : 'ltr'
  }, [lang])

  const t = useCallback((key) => DICT[lang][key] ?? DICT.ar[key] ?? key, [lang])
  const value = useMemo(() => ({ lang, setLang, t, languages: ['ar', 'en'] }), [lang, t])

  return <I18nContext.Provider value={value}>{children}</I18nContext.Provider>
}

export function useI18n() {
  const context = useContext(I18nContext)
  if (!context) throw new Error('useI18n must be used inside I18nProvider')
  return context
}
