/**
 * YALLA PHONE AI SECURITY — rule lexicon.
 *
 * Every rule is a deterministic pattern the server can evaluate without any
 * external AI provider, so the protection layer works 24/7 with zero credits.
 * Terms are stored in their normalized form (see `normalizeArabic`): the
 * matcher normalizes incoming text the same way, which is what makes
 * "كـلـب", "ك1ب" and "ك ل ب" collapse onto the same rule.
 *
 * An optional external moderation provider (OPENAI_API_KEY / MODERATION_API_URL)
 * is layered on top for images and video, see `media.ts`.
 */

export type Severity = 'low' | 'medium' | 'high' | 'critical';

export type Engine =
  | 'text'
  | 'image'
  | 'video'
  | 'voice'
  | 'fraud'
  | 'spam'
  | 'impersonation'
  | 'account';

